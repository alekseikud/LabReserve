-- Django creates accounts_user first. Domain tables are managed here, not by ORM models.
-- Keep the existing table names so databases created by the earlier setup retain data.
CREATE TABLE IF NOT EXISTS inventory_laboratory (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code varchar(24) NOT NULL UNIQUE,
    name varchar(120) NOT NULL,
    location varchar(160) NOT NULL
);

CREATE TABLE IF NOT EXISTS inventory_laboratory_managers (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    laboratory_id bigint NOT NULL REFERENCES inventory_laboratory(id) DEFERRABLE INITIALLY DEFERRED,
    user_id bigint NOT NULL REFERENCES accounts_user(id) DEFERRABLE INITIALLY DEFERRED,
    UNIQUE (laboratory_id, user_id)
);

CREATE TABLE IF NOT EXISTS inventory_equipment (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    laboratory_id bigint NOT NULL REFERENCES inventory_laboratory(id) DEFERRABLE INITIALLY DEFERRED,
    asset_tag varchar(40) NOT NULL UNIQUE,
    name varchar(120) NOT NULL,
    category varchar(80) NOT NULL,
    description text NOT NULL DEFAULT '',
    status varchar(16) NOT NULL DEFAULT 'available',
    created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT equipment_valid_status CHECK (status IN ('available', 'maintenance', 'retired'))
);

CREATE TABLE IF NOT EXISTS reservations_reservation (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id bigint NOT NULL REFERENCES accounts_user(id) DEFERRABLE INITIALLY DEFERRED,
    equipment_id bigint NOT NULL REFERENCES inventory_equipment(id) DEFERRABLE INITIALLY DEFERRED,
    purpose varchar(500) NOT NULL,
    starts_at timestamptz NOT NULL,
    ends_at timestamptz NOT NULL,
    status varchar(16) NOT NULL DEFAULT 'pending',
    created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT reservation_positive_interval CHECK (ends_at > starts_at),
    CONSTRAINT reservation_valid_status CHECK (status IN ('pending', 'approved', 'rejected', 'cancelled'))
);

CREATE INDEX IF NOT EXISTS equipment_lab_status_idx ON inventory_equipment (laboratory_id, status);
CREATE INDEX IF NOT EXISTS equipment_category_idx ON inventory_equipment (category);
CREATE INDEX IF NOT EXISTS reservation_owner_idx ON reservations_reservation (owner_id, status, starts_at);
CREATE INDEX IF NOT EXISTS reservation_equipment_idx ON reservations_reservation (equipment_id, starts_at, ends_at);
CREATE INDEX IF NOT EXISTS laboratory_manager_user_idx ON inventory_laboratory_managers (user_id);

-- Older tables used Python-side defaults. Supply the same defaults for SQL inserts.
ALTER TABLE inventory_equipment
    ALTER COLUMN description SET DEFAULT '',
    ALTER COLUMN status SET DEFAULT 'available',
    ALTER COLUMN created_at SET DEFAULT CURRENT_TIMESTAMP,
    ALTER COLUMN updated_at SET DEFAULT CURRENT_TIMESTAMP;
ALTER TABLE reservations_reservation
    ALTER COLUMN status SET DEFAULT 'pending',
    ALTER COLUMN created_at SET DEFAULT CURRENT_TIMESTAMP,
    ALTER COLUMN updated_at SET DEFAULT CURRENT_TIMESTAMP;

CREATE OR REPLACE FUNCTION labreserve_touch_updated_at() RETURNS trigger AS $$
BEGIN
    NEW.updated_at = statement_timestamp();
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE OR REPLACE TRIGGER equipment_updated_at
    BEFORE UPDATE ON inventory_equipment
    FOR EACH ROW EXECUTE FUNCTION labreserve_touch_updated_at();
CREATE OR REPLACE TRIGGER reservation_updated_at
    BEFORE UPDATE ON reservations_reservation
    FOR EACH ROW EXECUTE FUNCTION labreserve_touch_updated_at();
